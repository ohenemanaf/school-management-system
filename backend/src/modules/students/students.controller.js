const StudentModel = require('./students.model');
const UserModel = require('../users/users.model');
const bcrypt = require('bcrypt');
const crypto = require('crypto');
const emailService = require('../../utils/emailService');
class StudentController {
    static async getAll(req, res) {
        try {
            const students = await StudentModel.findAll();
            res.json(students);
        } catch (error) {
            console.error('Error fetching students:', error);
            res.status(500).json({ message: 'Server error' });
        }
    }

    static async getOne(req, res) {
        try {
            const student = await StudentModel.findById(req.params.id);
            if (!student) return res.status(404).json({ message: 'Student not found' });
            res.json(student);
        } catch (error) {
            console.error('Error fetching student:', error);
            res.status(500).json({ message: 'Server error' });
        }
    }

    static async create(req, res) {
        try {
            let { 
                email, password, firstName, lastName, enrollmentNumber, dateOfBirth, gender,
                address, guardianName, guardianPhone, medicalConditions, bloodGroup, studentGroupId
            } = req.body;

            let profileImageUrl = null;
            if (req.file) {
                profileImageUrl = `/uploads/profiles/${req.file.filename}`;
            }

            // 1. Check if user email already exists
            const existingUser = await UserModel.findByEmail(email);
            if (existingUser) return res.status(400).json({ message: 'Email already exists' });

            // 2. Auto-generate Index Number if missing
            if (!enrollmentNumber) {
                enrollmentNumber = await StudentModel.getNextEnrollmentNumber();
            }

            // 3. Auto-generate Temporary Password if missing
            const isAutoGeneratedPassword = !password;
            const finalPassword = password || crypto.randomBytes(4).toString('hex');

            // 4. Hash password and create User + Student within a transaction
            const salt = await bcrypt.genSalt(10);
            const passwordHash = await bcrypt.hash(finalPassword, salt);
            
            const studentId = await StudentModel.create({
                email, passwordHash, firstName, lastName, enrollmentNumber, dateOfBirth, gender,
                profileImageUrl, address, guardianName, guardianPhone, medicalConditions, bloodGroup, studentGroupId
            });

            // 5. Fire and forget welcome email
            emailService.sendWelcomeEmail(email, firstName, enrollmentNumber, finalPassword).catch(err => {
                console.error("Failed to send welcome email in background:", err);
            });

            res.status(201).json({ 
                message: 'Student created successfully', 
                studentId,
                credentials: isAutoGeneratedPassword ? { enrollmentNumber, password: finalPassword } : null
            });
        } catch (error) {
            console.error('Error creating student:', error);
            res.status(500).json({ message: 'Server error' });
        }
    }

    static async update(req, res) {
        try {
            const payload = { ...req.body };
            if (req.file) {
                payload.profileImageUrl = `/uploads/profiles/${req.file.filename}`;
            }

            const affected = await StudentModel.update(req.params.id, payload);
            if (affected === 0) return res.status(404).json({ message: 'Student not found' });
            res.json({ message: 'Student updated successfully' });
        } catch (error) {
            if (error.code === 'ER_DUP_ENTRY') {
                return res.status(400).json({ message: 'Email already exists' });
            }
            if (error.message === 'Student not found') {
                return res.status(404).json({ message: 'Student not found' });
            }
            console.error('Error updating student:', error);
            res.status(500).json({ message: 'Server error' });
        }
    }

    static async delete(req, res) {
        try {
            const success = await StudentModel.delete(req.params.id);
            if (!success) return res.status(404).json({ message: 'Student not found' });
            res.json({ message: 'Student deleted successfully' });
        } catch (error) {
            console.error('Error deleting student:', error);
            res.status(500).json({ message: 'Server error' });
        }
    }
}

module.exports = StudentController;
